#!/usr/bin/env bash
# Breakdown: turns the cut list into a readable cut sheet + YouTube chapters
# + a contact sheet (thumb grid) for visual review.
#
# Writes (filenames kept as-is; docs and the gate reference them):
#   DECUPAGEM.md          table: timeline position, file, day, duration, type, fill
#   CAPITULOS.txt         chapters ready to paste into the YouTube description
#   _build/contato/*.jpg  contact sheet, 1 thumb per cut
#
# Usage: bash _tools/decupagem.sh          (no thumbs, fast)
#        THUMBS=1 bash _tools/decupagem.sh (with contact sheet)
set -euo pipefail

BASE="${PROJ:-$PWD}"      # project root (_build/ and _out/ live here)
SRC="${SRC:-$BASE}"           # media folder
MAN="$BASE/_build/manifest.tsv"
EDL="$BASE/_build/edl.txt"
THUMBS="${THUMBS:-0}"
[ -f "$MAN" ] && [ -f "$EDL" ] || { echo "Missing manifest/edl. Run ingest.sh and roteiro.sh."; exit 1; }

# Temp files die on EXIT (see roteiro.sh).
DEC_TMPS="$BASE/_build/.dec.meta.$$.tmp $BASE/_build/.dec.edl.$$.tmp $BASE/_build/.dec.join.$$.tmp"
trap 'rm -f $DEC_TMPS' EXIT

DEC="$BASE/DECUPAGEM.md"
CAP="$BASE/CAPITULOS.txt"

# file -> day, original dur, real orientation
awk -F'\t' 'NR>1{
  rot=$6; w=$4; h=$5
  if (rot=="90"||rot=="-90"||rot=="270"||rot=="-270") { t=w; w=h; h=t }
  ori = (w>=h) ? "horiz" : "vert"
  split($9,a,"T")
  printf "%s\t%s\t%s\t%s\n", $1, a[1], $3, ori
}' "$MAN" | sort > "$BASE/_build/.dec.meta.$$.tmp"

grep -v '^#' "$EDL" | awk -F'\t' '{printf "%d\t%s\t%s\t%s\n", NR, $1, $2, $3}' \
  | sort -t$'\t' -k2,2 > "$BASE/_build/.dec.edl.$$.tmp"

join -t$'\t' -1 2 -2 1 "$BASE/_build/.dec.edl.$$.tmp" "$BASE/_build/.dec.meta.$$.tmp" \
  | sort -t$'\t' -k2,2n > "$BASE/_build/.dec.join.$$.tmp"
# columns: file, order, in, out, day, dur_orig, ori

# ---------- DECUPAGEM.md ----------
{
  echo "# Breakdown: vlog"
  echo
  echo "Generated by \`_tools/decupagem.sh\`. One row per cut, in video order."
  echo "To remove a cut: comment out its line in \`_build/edl.txt\` with \`#\` and run \`build.sh\`."
  echo
  awk -F'\t' '
  BEGIN {
    print "| # | starts at | cut | file | day | raw | used | type | framing |"
    print "|---|---|---|---|---|---|---|---|---|"
  }
  {
    file=$1; ord=$2; tin=$3; tout=$4; dia=$5; durorig=$6+0; ori=$7
    usado = tout - tin
    tipo = (durorig > 25) ? "**speech**" : (durorig > 6 ? "medium" : "b-roll")
    if (file ~ /\.(jpg|jpeg|png|PNG|JPG|heic)$/) tipo = "photo"
    enq = (ori == "vert") ? "vertical → blur" : "horizontal"
    h = int(acc/3600); m = int((acc%3600)/60); s = int(acc%60)
    printf "| %d | %02d:%02d:%02d | %.1fs | `%s` | %s | %.0fs | %.0f%% | %s | %s |\n",
           ord, h, m, s, usado, file, substr(dia,9,2)"/"substr(dia,6,2), durorig,
           (durorig>0 ? usado*100/durorig : 100), tipo, enq
    acc += usado
  }
  END {
    printf "\n**Total: %d cuts, %d min %02d s**\n", NR, int(acc/60), acc%60
  }' "$BASE/_build/.dec.join.$$.tmp"
} > "$DEC"

# ---------- CAPITULOS.txt (one block per day) ----------
{
  echo "# YouTube chapters: paste into the description"
  echo "# (YouTube requires the first one to be 00:00)"
  echo
  awk -F'\t' '
  {
    usado = $4 - $3; dia = $5
    if (dia != atual) {
      h = int(acc/3600); m = int((acc%3600)/60); s = int(acc%60)
      if (NR == 1) { h=0; m=0; s=0 }
      printf "%02d:%02d:%02d  Day %s/%s\n", h, m, s, substr(dia,9,2), substr(dia,6,2)
      atual = dia
    }
    acc += usado
  }' "$BASE/_build/.dec.join.$$.tmp"
} > "$CAP"

# ---------- contact sheet ----------
if [ "$THUMBS" = 1 ]; then
  TH="$BASE/_build/contato"; mkdir -p "$TH"; rm -f "$TH"/*.jpg
  echo "== extracting thumbs (1 per cut)"
  # FILE numbering is sequential with no gaps (tile reads %03d and stops at the first
  # one missing); the CUT number is drawn on the image.
  seq=0
  awk -F'\t' '{printf "%s\t%s\t%s\n", $2, $1, $3}' "$BASE/_build/.dec.join.$$.tmp" \
  | while IFS=$'\t' read -r ord file tin; do
      rotulo="$(printf '%03d' "$ord")"
      case "$(echo "${file##*.}" | tr 'A-Z' 'a-z')" in
        jpg|jpeg|png|heic) pos=() ;;                        # photo: -ss on a still fails
        *) pos=(-ss "$(awk -v t="$tin" 'BEGIN{printf "%.1f", t+0.3}')") ;;
      esac
      seq=$(( seq + 1 ))
      if ffmpeg -nostdin -y -v error "${pos[@]}" -i "$SRC/$file" -frames:v 1 \
        -vf "scale=320:180:force_original_aspect_ratio=decrease,pad=320:180:(ow-iw)/2:(oh-ih)/2:color=0x111111,drawtext=text='$rotulo':x=6:y=6:fontsize=22:fontcolor=white:box=1:boxcolor=black@0.6" \
        "$TH/$(printf '%03d' "$seq").jpg" 2>/dev/null
      then :; else seq=$(( seq - 1 )); echo "   ! no thumb: $file"; fi
    done
  n="$(ls "$TH"/*.jpg 2>/dev/null | wc -l)"
  if [ "$n" -gt 0 ]; then
    # this Windows ffmpeg build has no glob: input by numeric sequence
    ffmpeg -nostdin -y -v error -framerate 1 -start_number 1 -i "$TH/%03d.jpg" \
      -vf "tile=6x8:padding=4:color=0x111111" -frames:v 10 "$TH/folha-%02d.jpg" \
      || echo "   ! failed to assemble the sheet"
    echo "   $n thumbs, $(ls "$TH"/folha-*.jpg 2>/dev/null | wc -l) sheet(s) -> $TH"
  fi
fi

rm -f "$BASE/_build/.dec.meta.$$.tmp" "$BASE/_build/.dec.edl.$$.tmp" "$BASE/_build/.dec.join.$$.tmp"
echo "-> $DEC"
echo "-> $CAP"
sed -n '1,12p' "$CAP"
